let added = 0;
for (const n of NOTES) {
  const file = path.join(ROOT, n.cat, n.id + '.md');
  if (fs.existsSync(file)) continue; // 库里已有（含批准入库/手工修订的）→ 一个字都不碰
  const body = [
    '---',
    `id: ${n.cat}/${n.id}`,
    `分类: ${n.cat}`,
    `标题: ${n.title}`,
    `标签: ${n.tags.join('、')}`,
    `更新: ${TODAY}`,
    '权限: 只读——修改必须经阿珑同意（走待审区通道）',
    '---',
    '',
    n.body,
    '',
  ].join(NL);
  fs.writeFileSync(file, body, 'utf8');
  added++;
}

// 索引 = 扫描全库 front-matter 重建（任何新条目入库后重跑即同步）
function parseMeta(file) {
  const raw = fs.readFileSync(file, 'utf8');
  const m = raw.match(new RegExp('^---' + NL + '([\\s\\S]*?)' + NL + '---'));
  const meta = {};
  if (m) {
    for (const line of m[1].split(NL)) {
      const i = line.indexOf(':');
      if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
  }
  return meta;
}
const rows = [];
for (const cat of Object.keys(CATS)) {
  for (const f of fs.readdirSync(path.join(ROOT, cat)).filter((x) => x.endsWith('.md'))) {
    const meta = parseMeta(path.join(ROOT, cat, f));
    rows.push(`| ${cat} | ${f.slice(0, -3)} | ${meta['标题'] || f} | ${meta['标签'] || ''} |`);
  }
}
